import { test, expect } from "@playwright/test";
import { authenticateTestPage } from "./auth-helper";

test.beforeEach(async ({ page }) => authenticateTestPage(page));
test("shared dropdowns support modal selection, keyboard, controller updates and themes", async ({ page }) => {
  const errors: string[] = [];
  page.on("pageerror", (error) => errors.push(error.message));
  await page.goto("/");
  await expect(page.locator("#saveStatus")).toHaveAttribute("data-state", "saved", { timeout: 30000 });
  await page.locator('[data-view="sessions"]').click();
  await page.locator("#setupOpen").click();
  const deposit = page.getByRole("combobox", { name: "Начальный капитал, $", exact: true });
  await deposit.click();
  await expect(page.locator(".replay-select-menu:popover-open")).toBeVisible();
  await expect(page.locator(".replay-select-menu:popover-open [role=option]")).toHaveText(["$10,000", "$25,000", "$50,000", "$100,000", "$150,000", "$200,000", "$250,000"]);
  await page.getByRole("option", { name: "$25,000", exact: true }).click();
  await expect(page.locator("#sessionCapital")).toHaveValue("25000");
  await expect(deposit).toContainText("$25,000");
  await page.locator("#sessionCapital").selectOption("50000");
  await expect(deposit).toContainText("$50,000");
  await deposit.focus();
  await page.keyboard.press("ArrowDown");
  await expect(page.locator(".replay-select-menu:popover-open")).toBeVisible();
  await page.keyboard.press("Escape");
  await expect(page.locator(".replay-select-menu:popover-open")).toHaveCount(0);
  await expect(page.locator("#setupDialog")).toBeVisible();
  await deposit.click();
  await page.screenshot({ path: "/tmp/dropdown-deposit-dark.png" });
  await page.keyboard.press("Escape");
  await page.locator('[data-close="setupDialog"]').click();
  await page.locator("#themeToggle").click();
  await page.locator("#setupOpen").click();
  await deposit.click();
  await page.screenshot({ path: "/tmp/dropdown-deposit-light.png" });
  await page.keyboard.press("Escape");
  await page.setViewportSize({ width: 390, height: 844 });
  await deposit.click();
  const bounds = await page.locator(".replay-select-menu:popover-open").boundingBox();
  expect(bounds!.x).toBeGreaterThanOrEqual(0);
  expect(bounds!.x + bounds!.width).toBeLessThanOrEqual(391);
  expect(bounds!.y + bounds!.height).toBeLessThanOrEqual(845);
  await page.screenshot({ path: "/tmp/dropdown-deposit-mobile.png" });
  await page.keyboard.press("Escape");
  await page.locator('[data-close="setupDialog"]').click();
  await page.locator('[data-view="journal"]').click();
  const instrument = page.getByRole("combobox", { name: "Инструмент", exact: true });
  await instrument.click();
  await page.getByRole("option", { name: "ES", exact: true }).click();
  await expect(page.locator("#journalSymbol")).toHaveValue("ES");
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.locator('[data-view="replay"]').click();
  await page.locator("#settingsOpen").click();
  const timezone = page.getByRole("combobox", { name: "timezone", exact: true });
  await timezone.click();
  await page.getByRole("option", { name: "Moscow · MSK", exact: true }).click();
  await expect(page.locator("#prefTimezone")).toHaveValue("Europe/Moscow");
  await expect(timezone).toContainText("Moscow · MSK");
  await page.locator("#settingsCancel").click();
  expect(errors).toEqual([]);
});
